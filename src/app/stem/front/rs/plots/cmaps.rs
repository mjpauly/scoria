/// Sequential, perceptually-uniform colormap
#[allow(dead_code)]
pub fn viridis_plotly() -> ColorScale {
    to_plotly(&VIRIDIS)
}

/// Sequential, perceptually-uniform colormap
#[allow(dead_code)]
pub fn plasma_plotly() -> ColorScale {
    to_plotly(&PLASMA)
}

/// Cyclic, perceptually-uniform colormap
#[allow(dead_code)]
pub fn twilight_plotly() -> ColorScale {
    to_plotly(&TWILIGHT)
}

pub fn to_plotly(cmap: &[(f64, &'static str)]) -> ColorScale {
    ColorScale::Vector(
        cmap.iter()
            .map(|x| ColorScaleElement(x.0, x.1.to_string()))
            .collect(),
    )
}

/// Simple search for a close color for the input value (range in 0-1). Could be
/// sped up with binary_search_by
#[allow(dead_code)]
pub fn find_nearest(cmap: &'static [(f64, &str)], val: f64) -> &'static str {
    for pair in cmap {
        if val <= pair.0 {
            return pair.1;
        }
    }
    cmap.last().unwrap().1
}

/// Get the color of a data point inside the range [cmin-cmax]
pub fn get_data_color(
    cmap: &'static [(f64, &str)],
    val: f64,
    cmin: f64,
    cmax: f64,
) -> &'static str {
    let normalized = (val - cmin) / (cmax - cmin);
    find_nearest(cmap, normalized)
}

